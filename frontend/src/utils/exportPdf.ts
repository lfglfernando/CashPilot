import { REPORT_CURRENCY, formatMoney } from "./currency";
import { downloadBlob } from "./download";
import type { MonthlyReport } from "./monthlyReport";

function monthLabel(month: string): string {
  const [year, monthNumber] = month.split("-").map(Number);
  return new Date(year, monthNumber - 1, 1).toLocaleDateString("en-US", {
    month: "long",
    year: "numeric",
  });
}

// finds where the last table ended so the next one starts below it
// (jspdf-autotable adds lastAutoTable but TypeScript doesn't know about it)
function nextTableY(doc: object, gap = 10): number {
  const last = (doc as { lastAutoTable?: { finalY?: number } }).lastAutoTable;
  return (last?.finalY ?? 36) + gap;
}

export async function exportReportPdf(report: MonthlyReport): Promise<void> {
  // jsPDF is big so it only loads when you click Export PDF
  const [{ jsPDF }, { autoTable }] = await Promise.all([
    import("jspdf"),
    import("jspdf-autotable"),
  ]);

  const doc = new jsPDF();
  const margin = 14;
  const blue: [number, number, number] = [30, 64, 175];

  doc.setFontSize(18);
  doc.setTextColor(23, 37, 84);
  doc.text("CashPilot Monthly Report", margin, 20);

  doc.setFontSize(11);
  doc.setTextColor(71, 85, 105);
  doc.text(`${monthLabel(report.month)}  |  Currency: ${REPORT_CURRENCY}`, margin, 28);

  autoTable(doc, {
    startY: 36,
    head: [["Summary", "Amount"]],
    body: [
      ["Total Income", formatMoney(report.totalIncome)],
      ["Total Expenses", formatMoney(report.totalExpenses)],
      ["Net Profit", formatMoney(report.netProfit)],
    ],
    theme: "grid",
    headStyles: { fillColor: blue },
    columnStyles: { 1: { halign: "right" } },
    didParseCell: (data) => {
      if (data.section === "body" && data.row.index === 2) {
        data.cell.styles.fontStyle = "bold";
      }
    },
  });

  autoTable(doc, {
    startY: nextTableY(doc),
    head: [["Date", "Type", "Category", "Description", "Amount"]],
    body:
      report.transactions.length > 0
        ? report.transactions.map((t) => [
            t.time.slice(0, 10),
            t.type,
            t.category ?? "",
            t.description,
            formatMoney(t.amount),
          ])
        : [[{ content: "No transactions this month.", colSpan: 5 }]],
    theme: "striped",
    headStyles: { fillColor: blue },
    columnStyles: { 4: { halign: "right" } },
  });

  const pageCount = doc.getNumberOfPages();
  const generated = new Date().toLocaleDateString("en-US");
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  for (let page = 1; page <= pageCount; page++) {
    doc.setPage(page);
    doc.text(
      `Generated by CashPilot on ${generated}  |  Page ${page} of ${pageCount}`,
      margin,
      doc.internal.pageSize.getHeight() - 8,
    );
  }

  downloadBlob(doc.output("blob"), `cashpilot-report-${report.month}.pdf`);
}
